use crate::engine::PummelError;
use crate::models::config::Configuration;

/// Validates that a configuration has at least one scenario and execution plan,
/// and that all execution plans reference existing scenarios.
///
/// # Errors
///
/// Returns `PummelError::Validation` if the configuration is empty or malformed.
pub fn validate_taurus_compatibility(config: &Configuration) -> Result<(), PummelError> {
    if config.scenarios.is_empty() {
        return Err(PummelError::Validation {
            field: "scenarios".to_string(),
            reason: "At least one scenario is required for Taurus export".to_string(),
        });
    }

    if config.execution.is_empty() {
        return Err(PummelError::Validation {
            field: "execution".to_string(),
            reason: "At least one execution plan is required for Taurus export".to_string(),
        });
    }

    for (i, plan) in config.execution.iter().enumerate() {
        if !config.scenarios.contains_key(&plan.scenario) {
            return Err(PummelError::Validation {
                field: format!("execution[{i}].scenario"),
                reason: format!(
                    "Execution plan references non-existent scenario '{}'",
                    plan.scenario
                ),
            });
        }
    }

    Ok(())
}

/// Exports a Pummel `Configuration` into canonical Taurus-compatible YAML.
///
/// # Errors
///
/// Returns `PummelError::Validation` or `PummelError::Serde` if validation or serialization fails.
pub fn export_taurus(config: &Configuration) -> Result<String, PummelError> {
    validate_taurus_compatibility(config)?;

    let yaml_body = serde_yaml::to_string(config).map_err(|e| PummelError::Serde {
        message: format!("Failed to serialize canonical Taurus YAML: {e}"),
        file_path: None,
        source: None,
    })?;

    let mut output = String::new();
    output.push_str("# Canonical Taurus YAML Configuration\n");
    output.push_str("# Generated by Pummel (https://github.com/py-centric/pummel)\n");
    output.push_str("# Compatible with BlazeMeter and bzt runner\n\n");
    output.push_str(&yaml_body);

    Ok(output)
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::models::config::*;
    use std::collections::HashMap;

    #[test]
    fn test_export_taurus_basic() {
        let mut scenarios = HashMap::new();
        scenarios.insert(
            "smoke".to_string(),
            ScenarioDefinition {
                requests: vec![HTTPRequestDefinition::Simple(
                    "http://localhost:8080/health".to_string(),
                )],
                weight: 1,
                think_time: Some("100ms".to_string()),
                data_sources: None,
                headers: None,
            },
        );

        let config = Configuration {
            execution: vec![ExecutionPlan {
                concurrency: 5,
                ramp_up: "2s".to_string(),
                hold_for: "10s".to_string(),
                scenario: "smoke".to_string(),
                throughput: None,
                steps: None,
                pacing: None,
            }],
            scenarios,
            reporting: vec![],
            services: vec![],
            api: None,
        };

        let yaml = export_taurus(&config).expect("taurus export should succeed");
        assert!(yaml.contains("concurrency: 5"));
        assert!(yaml.contains("scenario: smoke"));
        assert!(yaml.contains("http://localhost:8080/health"));
    }

    #[test]
    fn test_validate_taurus_empty_scenarios() {
        let config = Configuration {
            execution: vec![ExecutionPlan {
                concurrency: 1,
                ramp_up: "0s".to_string(),
                hold_for: "1s".to_string(),
                scenario: "missing".to_string(),
                throughput: None,
                steps: None,
                pacing: None,
            }],
            scenarios: HashMap::new(),
            reporting: vec![],
            services: vec![],
            api: None,
        };
        let res = export_taurus(&config);
        assert!(matches!(res, Err(PummelError::Validation { field, .. }) if field == "scenarios"));
    }

    #[test]
    fn test_validate_taurus_empty_execution() {
        let mut scenarios = HashMap::new();
        scenarios.insert(
            "test".to_string(),
            ScenarioDefinition {
                requests: vec![],
                weight: 1,
                think_time: None,
                data_sources: None,
                headers: None,
            },
        );
        let config = Configuration {
            execution: vec![],
            scenarios,
            reporting: vec![],
            services: vec![],
            api: None,
        };
        let res = export_taurus(&config);
        assert!(matches!(res, Err(PummelError::Validation { field, .. }) if field == "execution"));
    }

    #[test]
    fn test_validate_taurus_missing_scenario_reference() {
        let mut scenarios = HashMap::new();
        scenarios.insert(
            "existing".to_string(),
            ScenarioDefinition {
                requests: vec![],
                weight: 1,
                think_time: None,
                data_sources: None,
                headers: None,
            },
        );
        let config = Configuration {
            execution: vec![ExecutionPlan {
                concurrency: 1,
                ramp_up: "0s".to_string(),
                hold_for: "1s".to_string(),
                scenario: "nonexistent".to_string(),
                throughput: None,
                steps: None,
                pacing: None,
            }],
            scenarios,
            reporting: vec![],
            services: vec![],
            api: None,
        };
        let res = export_taurus(&config);
        assert!(
            matches!(res, Err(PummelError::Validation { field, .. }) if field == "execution[0].scenario")
        );
    }
}
